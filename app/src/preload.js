// Preload (o "garçom"): expõe para a tela só o que ela pode pedir.
const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('hub', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (changes, confirmClose) => ipcRenderer.invoke('settings:save', changes, confirmClose),
  listEngines: () => ipcRenderer.invoke('engines:list'),
  listHarnesses: () => ipcRenderer.invoke('harness:list'),
  createHarness: details => ipcRenderer.invoke('harness:create', details),
  setHarnessWorkdir: (harness, workdir) => ipcRenderer.invoke('harness:setWorkdir', { harness, workdir }),
  getHarnessStructure: harness => ipcRenderer.invoke('harness:getStructure', harness),
  listMiniapps: () => ipcRenderer.invoke('miniapps:list'),
  openMiniapp: name => ipcRenderer.invoke('miniapp:open', name),
  listSessions: harness => ipcRenderer.invoke('session:list', harness),
  openSession: req => ipcRenderer.invoke('session:open', req),
  deleteSession: (harness, sessionId) => ipcRenderer.invoke('session:delete', { harness, sessionId }),

  write: (id, data) => ipcRenderer.send('terminal:write', { id, data }),
  resize: (id, cols, rows) => ipcRenderer.send('terminal:resize', { id, cols, rows }),
  kill: id => ipcRenderer.send('terminal:kill', id),

  getUsage: () => ipcRenderer.invoke('usage:get'),
  refreshUsage: () => ipcRenderer.invoke('usage:refresh'),
  onUsage: cb => ipcRenderer.on('usage:update', (_e, state) => cb(state)),

  listFiles: (harness, rel) => ipcRenderer.invoke('files:list', { harness, rel }),
  readHarnessFile: (harness, rel) => ipcRenderer.invoke('files:readHarness', { harness, rel }),
  openFile: (harness, rel) => ipcRenderer.invoke('files:open', { harness, rel }),
  revealFile: (harness, rel) => ipcRenderer.invoke('files:reveal', { harness, rel }),
  readFile: (harness, rel) => ipcRenderer.invoke('files:read', { harness, rel }),
  writeFile: (harness, rel, text) => ipcRenderer.invoke('files:write', { harness, rel, text }),
  createEntry: (harness, rel, dir, text) => ipcRenderer.invoke('files:create', { harness, rel, dir, text }),
  removePatch: (harness, rel) => ipcRenderer.invoke('files:remove', { harness, rel }),
  drawPreview: (harness, rel, png, summary, suffix) => ipcRenderer.invoke('draw:preview', { harness, rel, png, summary, suffix }),
  setTabDrawings: (harness, sessionId, tabId, drawings) => ipcRenderer.invoke('session:tabDrawings', { harness, sessionId, tabId, drawings }),
  openExternal: url => ipcRenderer.invoke('shell:openExternal', url),
  browseFolder: () => ipcRenderer.invoke('dialog:browse-folder'),
  deleteFile: (harness, rel) => ipcRenderer.invoke('files:delete', { harness, rel }),
  moveFile: (harness, srcRel, destFolder) => ipcRenderer.invoke('files:move', { harness, srcRel, destFolder }),
  renameFile: (harness, rel, newName) => ipcRenderer.invoke('files:rename', { harness, rel, newName }),
  importFile: (harness, externalPath, destFolder) => ipcRenderer.invoke('files:import', { harness, externalPath, destFolder }),
  filePath: (harness, rel) => ipcRenderer.invoke('files:path', { harness, rel }),
  onFilesChanged: cb => ipcRenderer.on('files:changed', (_e, payload) => cb(payload)),


  toggleFullscreen: () => ipcRenderer.invoke('window:toggleFullscreen'),
  isFullscreen: () => ipcRenderer.invoke('window:isFullscreen'),
  minimizeWindow: () => ipcRenderer.invoke('window:minimize'),
  maximizeWindow: () => ipcRenderer.invoke('window:maximize'),
  closeWindow: () => ipcRenderer.invoke('window:close'),
  isMaximized: () => ipcRenderer.invoke('window:isMaximized'),

  // navegador embutido (multi-tab)
  browserNewTab: (url) => ipcRenderer.invoke('browser:new-tab', url),
  browserCloseTab: (id) => ipcRenderer.invoke('browser:close-tab', id),
  browserSwitchTab: (id) => ipcRenderer.invoke('browser:switch-tab', id),
  showBrowser: (bounds) => ipcRenderer.invoke('browser:show', bounds),
  hideBrowser: () => ipcRenderer.invoke('browser:hide'),
  navigateBrowser: (url) => ipcRenderer.invoke('browser:navigate', url),
  browserBack: () => ipcRenderer.invoke('browser:go-back'),
  browserForward: () => ipcRenderer.invoke('browser:go-forward'),
  browserReload: () => ipcRenderer.invoke('browser:reload'),
  browserInfo: () => ipcRenderer.invoke('browser:get-info'),
  setBrowserBounds: (b) => ipcRenderer.invoke('browser:set-bounds', b),
  listAutomations: harness => ipcRenderer.invoke('automation:list', { harness }),
  runAutomation: (harness, rel) => ipcRenderer.invoke('automation:run', { harness, rel }),
  cancelAutomation: () => ipcRenderer.invoke('automation:cancel'),
  startAutomationRecording: () => ipcRenderer.invoke('automation:record-start'),
  stopAutomationRecording: (harness, name) => ipcRenderer.invoke('automation:record-stop', { harness, name }),
  onBrowserAutomation: cb => ipcRenderer.on('browser:automation', (_e, data) => cb(data)),
  extractBrowserPage: () => ipcRenderer.invoke('browser:extract'),
  getBrowserTabs: () => ipcRenderer.invoke('browser:get-tabs'),
  getBrowserClosedTabs: () => ipcRenderer.invoke('browser:get-closed-tabs'),
  reopenBrowserClosedTab: () => ipcRenderer.invoke('browser:reopen-closed-tab'),
  onBrowserNavigated: cb => ipcRenderer.on('browser:navigated', (_e, data) => cb(data)),
  onBrowserTabs: cb => ipcRenderer.on('browser:tabs', (_e, data) => cb(data)),
  onBrowserDownload: cb => ipcRenderer.on('browser:download', (_e, data) => cb(data)),

  onData: cb => ipcRenderer.on('terminal:data', (_e, msg) => cb(msg)),
  onExit: cb => ipcRenderer.on('terminal:exit', (_e, msg) => cb(msg))
})
